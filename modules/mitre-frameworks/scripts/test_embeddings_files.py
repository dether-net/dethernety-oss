#!/usr/bin/env python3
"""
Tests for check_embeddings_files.py and load_committed_data.py's statement split, without
a database.

The file check runs on small generated files: a matching file passes, and each way a file
can disagree with the manifest's profile fails (another model in the header or a SET, a
mixed file, a missing label or a wrong row count, a short or non-unit vector, a missing
file, a Profile header naming another id, a truncated file, an appended statement that is
not one model-stamping UNWIND batch); a second Model header is ignored, as Go ignores it.
It also runs on the committed files against the committed manifest. Both splits are checked
against the Go splitter's reference output for oss/pkg/cypher/testdata/synthetic.cypher,
and the check's own splitter against the Go splitter's edge cases.
"""

from __future__ import annotations

import json
import math
import sys
import tempfile
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from check_embeddings_files import DIMENSIONS, EXPECTED_ROWS, check_file, check_module, parse_statements  # noqa: E402
from load_committed_data import LOAD_FILES, node_keys, parse_cypher_statements  # noqa: E402

MODULE_DIR = Path(__file__).resolve().parent.parent
PROFILE = "embeddinggemma-300m-retrieval-v1"
SMALL = {"MitreAtlasTechnique": 3, "MitreAtlasMitigation": 2}


def unit(seed: int, dims: int = DIMENSIONS) -> List[float]:
    v = [math.sin(seed * 7.0 + i) for i in range(dims)]
    norm = math.sqrt(sum(x * x for x in v))
    return [x / norm for x in v]


def embeddings_file(
    rows: Dict[str, int],
    model: str = PROFILE,
    header_model: Optional[str] = None,
    profile_header: Optional[str] = PROFILE,
    vector: Callable[[int], List[float]] = unit,
    set_models: Optional[Dict[str, str]] = None,
) -> str:
    """A file in the exporter's shape: header, then one UNWIND block per label."""
    out = [
        "// Generated by mitre-frameworks export_embeddings_to_cypher.py at 2026-10-15T00:00:00+00:00",
        f"// Model: {header_model or model}  Dimensions: {DIMENSIONS}",
    ]
    if profile_header:
        out.append(f"// Profile: {profile_header}  Weights: org/m@{'a' * 40}  dtype: fp32  Document prompt: title = name")
    out += ["// Source: mitre-frameworks build", ""]
    seed = 0
    for label, n in rows.items():
        out.append("UNWIND [")
        for i in range(n):
            seed += 1
            sep = "," if i < n - 1 else ""
            out.append(f'  {{ atlas_id: "{label}-{i}", embedding: {json.dumps(vector(seed))} }}{sep}')
        out += [
            "] AS row",
            f"MATCH (n:{label} {{atlas_id: row.atlas_id}})",
            "SET n.embedding = row.embedding,",
            f'    n.embeddingModel = "{(set_models or {}).get(label, model)}";',
            "",
        ]
    return "\n".join(out)


def check(text: str, expected: Dict[str, int] = SMALL) -> List[str]:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "09-atlas-embeddings.cypher"
        path.write_text(text, encoding="utf-8")
        return check_file(path, PROFILE, expected)


def fails_with(text: str, contains: str, expected: Dict[str, int] = SMALL) -> None:
    problems = check(text, expected)
    assert any(contains in p for p in problems), f"{contains!r} not in {problems}"


def a_matching_file_passes() -> None:
    assert check(embeddings_file(SMALL)) == []


def an_onnx_profile_needs_its_profile_line() -> None:
    fails_with(embeddings_file(SMALL, profile_header=None), "0 Profile header lines, expected 1")
    two = embeddings_file(SMALL).replace("// Source:", f"// Profile: {PROFILE}  again\n// Source:")
    fails_with(two, "2 Profile header lines, expected 1")


def the_legacy_profile_has_no_profile_line() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "09-atlas-embeddings.cypher"
        path.write_text(embeddings_file(SMALL, model="embeddinggemma", profile_header=None), encoding="utf-8")
        assert check_file(path, "embeddinggemma", SMALL) == []
        path.write_text(embeddings_file(SMALL, model="embeddinggemma", profile_header="embeddinggemma"), encoding="utf-8")
        assert any("1 Profile header lines, expected 0" in p for p in check_file(path, "embeddinggemma", SMALL))


def a_batch_without_its_set_fails() -> None:
    text = embeddings_file(SMALL)
    first = text.index('    n.embeddingModel = ')
    end = text.index("\n", first)
    broken = text[:first].rstrip(",\n") + ";" + text[end:]
    fails_with(broken, "statement 0 is not one UNWIND batch for one label that sets embeddingModel")


def another_model_fails() -> None:
    fails_with(embeddings_file(SMALL, model="embeddinggemma", profile_header=None), "the Model header is ('embeddinggemma', 768)")
    fails_with(embeddings_file(SMALL, header_model="embeddinggemma"), "the Model header is ('embeddinggemma', 768)")
    fails_with(embeddings_file(SMALL, set_models={"MitreAtlasMitigation": "embeddinggemma"}), "statement 1 sets embeddingModel 'embeddinggemma', expected 'embeddinggemma-300m-retrieval-v1'")
    fails_with(embeddings_file(SMALL, profile_header="embeddinggemma-2-text-retrieval-v1"), "the Profile header names 'embeddinggemma-2-text-retrieval-v1'")


def a_wrong_row_count_or_a_missing_label_fails() -> None:
    fails_with(embeddings_file({"MitreAtlasTechnique": 3, "MitreAtlasMitigation": 1}), "rows per label are")
    fails_with(embeddings_file({"MitreAtlasTechnique": 3}), "rows per label are")
    truncated = embeddings_file(SMALL).split("] AS row")
    fails_with("] AS row".join(truncated[:-1]) + "] AS row\n", "rows per label are")


def a_bad_vector_fails() -> None:
    fails_with(embeddings_file(SMALL, vector=lambda s: unit(s, DIMENSIONS - 1)), "without 768 finite numbers")
    fails_with(embeddings_file(SMALL, vector=lambda s: [2 * x for x in unit(s)]), "not unit length")


def rows_after_the_last_match_fail() -> None:
    text = embeddings_file(SMALL) + '\nUNWIND [\n  { atlas_id: "x", embedding: ' + json.dumps(unit(99)) + " }\n] AS row\n"
    fails_with(text, "statement 2 is not one UNWIND batch")


def an_extra_statement_fails() -> None:
    # A statement of any other kind fails, wherever it sits, however well the batches read.
    fails_with(embeddings_file(SMALL) + "\nMATCH (n) DETACH DELETE n;\n", "statement 2 is not one UNWIND batch")
    text = embeddings_file(SMALL)
    first_batch_end = text.index('";') + 2
    fails_with(text[:first_batch_end] + "\nRETURN 1;" + text[first_batch_end:], "statement 1 is not one UNWIND batch")


def a_second_model_stamping_statement_fails() -> None:
    # The finding's restamp: no rows, no `{key:` MATCH; it must not pass for its embeddingModel SET.
    restamp = '\nMATCH (n:MitreAtlasTechnique) SET n.embeddingModel = "embeddinggemma", n.embedding = [0.0];\n'
    fails_with(embeddings_file(SMALL) + restamp, "statement 2 is not one UNWIND batch")
    # A batch that stamps embeddingModel twice, each on a line of its own as the exporter writes it.
    text = embeddings_file(SMALL)
    first = text.index('    n.embeddingModel = ')
    twice = text[:first] + '    n.embeddingModel = "embeddinggemma"\nWITH n SET\n' + text[first:]
    fails_with(twice, "statement 0 is not one UNWIND batch")
    # A second batch that re-embeds a label in the profile's name still changes the row count.
    batches = text.split("\n\n", 1)[1].split(";\n")
    fails_with(text + "\n" + batches[0] + ";\n", "rows per label are {'MitreAtlasTechnique': 6, 'MitreAtlasMitigation': 2}")


def two_model_headers_use_the_first() -> None:
    text = embeddings_file(SMALL)
    other = f"// Model: embeddinggemma  Dimensions: {DIMENSIONS}\n"
    assert check(text.replace("// Source:", other + "// Source:")) == []
    fails_with(other + text, "the Model header is ('embeddinggemma', 768)")


def a_truncated_file_fails() -> None:
    fails_with(embeddings_file(SMALL) + '\nUNWIND [\n  { atlas_id: "x', "the file does not parse: unterminated string literal")
    fails_with(embeddings_file(SMALL) + "\n/* cut", "the file does not parse: unterminated block comment")


def a_missing_file_fails() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        assert check_file(Path(tmp) / "05-mitre-embeddings.cypher", PROFILE, SMALL) == ["05-mitre-embeddings.cypher: missing"]


def the_manifest_must_name_a_profile() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "manifest.json").write_text('{"name": "mitre-frameworks"}', encoding="utf-8")
        assert check_module(Path(tmp)) == ["manifest.json: no embeddingProfile"]


def the_committed_files_match_the_committed_manifest() -> None:
    assert check_module(MODULE_DIR) == []
    assert set(EXPECTED_ROWS) == {"05-mitre-embeddings.cypher", "09-atlas-embeddings.cypher"}


def splits_like_the_go_reference() -> None:
    synthetic = MODULE_DIR.parent.parent / "pkg" / "cypher" / "testdata" / "synthetic.cypher"
    want = [
        "CREATE (a:N {name: 'has ; semicolon'})",
        'MATCH (n) WHERE n.s = "double ; quote" SET n.x = 1',
        "CREATE (b {q: 'escaped \\' quote ; here'})",
        'MERGE (c {p: "esc \\" dq ; x"})',
    ]
    assert parse_cypher_statements(synthetic.read_text(encoding="utf-8")) == want
    assert parse_statements(synthetic.read_text(encoding="utf-8")) == want


def the_check_splits_like_the_go_edge_cases() -> None:
    # oss/pkg/cypher/parse_test.go, TestParseStatementsEdgeCases.
    cases = [
        ("", []),
        ("  ;\n;\t;", []),
        ("RETURN 1", ["RETURN 1"]),
        ("CREATE ({s:'a;b'})", ["CREATE ({s:'a;b'})"]),
        ('CREATE ({s:"a;b"})', ['CREATE ({s:"a;b"})']),
        ("A // c ; c\nB;", ["A \nB"]),
        ("A /* ; ; */ B;", ["A  B"]),
        ("X ({s:'a\\'b;c'}) ;", ["X ({s:'a\\'b;c'})"]),
        ('SET p = "C:\\\\"; CREATE (x);', ['SET p = "C:\\\\"', "CREATE (x)"]),
        ("MATCH (n:`a;b`) RETURN n", ["MATCH (n:`a", "b`) RETURN n"]),
    ]
    for text, want in cases:
        assert parse_statements(text) == want, (text, parse_statements(text), want)
    for text in ("MATCH (n) WHERE n.x = 'oops", "CREATE (a); /* unfinished"):
        try:
            parse_statements(text)
        except ValueError:
            continue
        raise AssertionError(f"no error for {text!r}")


def finds_the_node_keys_of_the_committed_files() -> None:
    keys = node_keys((MODULE_DIR / "data" / f).read_text(encoding="utf-8") for f in LOAD_FILES)
    labels = {label for label, _ in keys}
    for label in ("MitreAttackTechnique", "MitreDefendTechnique", "MitreAttackMitigation", "MitreAtlasTechnique", "MitreAtlasMitigation"):
        assert label in labels, (label, keys)
    assert ("MitreAttackTechnique", "attack_id") in keys and ("MitreAtlasTechnique", "atlas_id") in keys


def main_tests() -> int:
    cases: List[Callable[[], None]] = [
        a_matching_file_passes,
        an_onnx_profile_needs_its_profile_line,
        the_legacy_profile_has_no_profile_line,
        a_batch_without_its_set_fails,
        another_model_fails,
        a_wrong_row_count_or_a_missing_label_fails,
        a_bad_vector_fails,
        rows_after_the_last_match_fail,
        an_extra_statement_fails,
        a_second_model_stamping_statement_fails,
        two_model_headers_use_the_first,
        a_truncated_file_fails,
        a_missing_file_fails,
        the_manifest_must_name_a_profile,
        the_committed_files_match_the_committed_manifest,
        splits_like_the_go_reference,
        the_check_splits_like_the_go_edge_cases,
        finds_the_node_keys_of_the_committed_files,
    ]
    failures = 0
    for case in cases:
        try:
            case()
            print(f"ok   {case.__name__}")
        except Exception as err:  # noqa: BLE001
            failures += 1
            print(f"FAIL {case.__name__}: {type(err).__name__}: {err}")
    print(f"{len(cases) - failures} passed, {failures} failed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main_tests())
