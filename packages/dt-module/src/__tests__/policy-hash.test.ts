/**
 * The policy hash helper: what a class's `policyHash` is computed over. Every producer of the value goes through it,
 * so a change here moves every stored hash and marks every element evaluated under an unchanged policy as stale.
 */
import { describe, it, expect } from 'vitest';
import { createHash } from 'crypto';
import { NO_POLICY_HASH, decodePolicySource, policySourceHash } from '../policy-hash';
import { POLICY_HASH_GOLDEN_HEX, POLICY_HASH_GOLDEN_POLICY } from '../testing/fixtures';

const sha256 = (text: string) => createHash('sha256').update(text).digest('hex');

const SOURCE = 'package t.expo\n\nexposures contains {"name": "E"} if {\n    input.public == true\n}';

describe('decodePolicySource', () => {
  it('returns a policy that starts with its package as given', () => {
    expect(decodePolicySource(SOURCE)).toBe(SOURCE);
  });

  it('decodes a base64-encoded policy', () => {
    expect(decodePolicySource(Buffer.from(SOURCE, 'utf-8').toString('base64'))).toBe(SOURCE);
  });

  it('returns a policy that opens with a comment as given, rather than misreading it as base64', () => {
    const generated = `# GENERATED by the pack compiler. Do not edit.\n${SOURCE}`;
    expect(decodePolicySource(generated)).toBe(generated);
  });

  it('is null for no policy', () => {
    expect(decodePolicySource('')).toBeNull();
    expect(decodePolicySource(null)).toBeNull();
    expect(decodePolicySource(undefined)).toBeNull();
  });
});

describe('policySourceHash', () => {
  it('is the sha256 hex of a plain policy', () => {
    expect(policySourceHash(SOURCE)).toBe(sha256(SOURCE));
  });

  it('is the hash of the decoded source for a base64-encoded policy', () => {
    expect(policySourceHash(Buffer.from(SOURCE, 'utf-8').toString('base64'))).toBe(sha256(SOURCE));
  });

  it('hashes a policy that opens with a comment as it stands', () => {
    const generated = `# GENERATED by the pack compiler. Do not edit.\n${SOURCE}`;
    expect(policySourceHash(`${generated}\n`)).toBe(sha256(generated));
  });

  it('ignores surrounding whitespace, so a committed file ending in a newline hashes as its source', () => {
    expect(policySourceHash(`${SOURCE}\n`)).toBe(sha256(SOURCE));
    expect(policySourceHash(`\n  ${SOURCE}\n\n\t \n`)).toBe(sha256(SOURCE));
  });

  it('is the hash of the empty source for an empty or blank policy', () => {
    expect(NO_POLICY_HASH).toBe(sha256(''));
    expect(policySourceHash('')).toBe(NO_POLICY_HASH);
    expect(policySourceHash(' \n\t\n')).toBe(NO_POLICY_HASH);
  });
});

describe('the policy hash golden', () => {
  it('ends in a closing brace and a newline, as a committed policy does', () => {
    expect(POLICY_HASH_GOLDEN_POLICY.endsWith('}\n')).toBe(true);
  });

  it('hashes to its recorded value', () => {
    expect(policySourceHash(POLICY_HASH_GOLDEN_POLICY)).toBe(POLICY_HASH_GOLDEN_HEX);
    expect(POLICY_HASH_GOLDEN_HEX).toBe(sha256(POLICY_HASH_GOLDEN_POLICY.trim()));
  });
});
