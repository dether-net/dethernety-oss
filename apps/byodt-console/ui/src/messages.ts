// Operator-facing sentences that more than one panel shows.
//
// ONE SENTENCE, ONE DEFINITION, and a file rather than a constant beside one of its readers. Several
// panels show this line — the catalog, the artifacts, the disconnect control and the card that chooses who
// may sign in — and a copy per panel is the drift this rule exists to prevent: two literals whose whole
// purpose is being one literal. A file boundary is not a reason the rule stops applying.
//
// The daemon states the same fact in its own refusal, in Go, and that copy is deliberately NOT bound to
// this one: it is a REFUSAL — what happened, and that nothing changed — while this is a TOOLTIP explaining
// why a control is unavailable before anything is attempted. Different jobs, different sentences, and a
// parity test over prose would only make both harder to improve.

/**
 * Why an admin-only control is unavailable, and who can change that. It names both things the role
 * covers — changing the deployment, and seeing who may sign in to it — because the card that shows the
 * team's members is gated for what it reveals rather than for what it changes, and a sentence about
 * changing alone would be false there.
 */
export const ADMIN_ONLY =
  'Only an administrator of this deployment’s team can change what it provides or see who may sign in to it. An owner or administrator of that team can grant you the administrator role in the portal.'
